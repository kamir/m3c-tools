// kindReport returns the report of one synthetic bundle per kind.
func kindReport(t *testing.T, kind trustfreeze.Kind) Report {
	t.Helper()
	dir := t.TempDir()
	if kind == trustfreeze.KindDiff {
		_, _, d, v := scenario(t, dir)
		r, err := FromBundle(writeDiffBundle(t, dir, d, &v))
		if err != nil {
			t.Fatal(err)
		}
		return r
	}
	b := writeCapture(t, dir, "bundle", kind, testTime, "24.04", 0)
	r, err := FromBundle(b)
	if err != nil {
		t.Fatal(err)
	}
	return r
}

