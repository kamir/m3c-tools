// TestReportHTMLTwiceTheSameBytes: the page of one report is the same bytes
// every time, so two printouts of the same bundle are comparable.
func TestReportHTMLTwiceTheSameBytes(t *testing.T) {
	for _, r := range everyKindOfReport(t) {
		first, err := MarshalHTML(r, HTMLOptions{Generator: htmlTestGenerator})
		if err != nil {
			t.Fatal(err)
		}
		for i := 0; i < 8; i++ {
			again, err := MarshalHTML(r, HTMLOptions{Generator: htmlTestGenerator})
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(first, again) {
				t.Fatalf("%s: run %d differs from the first run", r.Input.Kind, i+2)
			}
		}
	}
}

// TestReportHTMLHasNoExternalReference: the page opens on a host without a
// network, so it names no address, loads no script, no stylesheet and no font,
// and carries no data URI. The check reads the generated bytes, not the
// template: a template can be clean and a value carry an address into it.
func TestReportHTMLHasNoExternalReference(t *testing.T) {
	for _, r := range everyKindOfReport(t) {
		page, err := MarshalHTML(r, HTMLOptions{Generator: htmlTestGenerator})
		if err != nil {
			t.Fatal(err)
		}
		if found := externalReferences(string(page)); len(found) > 0 {
			t.Fatalf("%s: the page carries %d external reference(s):\n%s",
				r.Input.Kind, len(found), strings.Join(found, "\n"))
		}
		// No attribute of that class at all, jump target included: the page
		// has no links.
		if n := len(attributeNames(string(page), "href", "src")); n > 0 {
			t.Fatalf("%s: the page carries %d href/src attribute(s)", r.Input.Kind, n)
		}
	}
}

// TestExternalReferenceCheckFindsAPlantedReference is the counter-probe: a
// check that only ever runs against the real page proves that it can be green,
// not that it can search. Each planted reference must be found, and the one
// allowed form (a jump target inside the document) must not.
func TestExternalReferenceCheckFindsAPlantedReference(t *testing.T) {
	page, err := MarshalHTML(kindReport(t, trustfreeze.KindCapture), HTMLOptions{Generator: htmlTestGenerator})
	if err != nil {
		t.Fatal(err)
	}
	base := string(page)
	if found := externalReferences(base); len(found) > 0 {
		t.Fatalf("the page is not clean to begin with: %v", found)
	}
	for _, tc := range []struct {
		name    string
		planted string
		where   string
	}{
		{"a stylesheet link", `<link rel="stylesheet" href="https://example.invalid/a.css">`, "</head>"},
		{"a script element", `<script src="https://example.invalid/d.js"></script>`, "</head>"},
		{"an at-import in the style block", "@import url(\"https://example.invalid/b.css\");\n", "</style>"},
		{"a url() in the style block", "body { background: url(https://example.invalid/c.png); }\n", "</style>"},
		{"an inline style with a url()", `<div style="background: url(https://example.invalid/e.png)"></div>`, "</body>"},
		{"a data URI image", `<img src="data:image/png;base64,iVBORw0KGgo=">`, "</body>"},
		{"a web font in the style block", "@font-face { font-family: x; src: url(x.woff2); }\n", "</style>"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			at := strings.Index(base, tc.where)
			if at < 0 {
				t.Fatalf("the page has no %s to plant before", tc.where)
			}
			planted := base[:at] + tc.planted + base[at:]
			if found := externalReferences(planted); len(found) == 0 {
				t.Fatalf("the check did not find the planted %s", tc.planted)
			}
		})
	}
	t.Run("a jump target inside the document is allowed", func(t *testing.T) {
		at := strings.Index(base, "</body>")
		planted := base[:at] + `<a href="#state">state</a>` + base[at:]
		if found := externalReferences(planted); len(found) > 0 {
			t.Fatalf("a jump target inside the document was refused: %v", found)
		}
	})
}

// TestReportHTMLShowsHostileContentAsText: a value out of a host that looks
// like an address or like markup is content, not a reference. The page shows
// it, escaped, and the external-reference check stays green. This is the same
// statement from the other side: the check reads markup, not strings.
func TestReportHTMLShowsHostileContentAsText(t *testing.T) {
	const addr = "https://boese.invalid/x"
	const markup = "<script>alert(1)</script>"
	r := reportWithAttributes(map[string]string{"os_family": "linux"})
	r.Capture.Probes = []trustfreeze.ProbeSummary{{
		ProbeID: "linux.motd", Status: trustfreeze.StatusPartial,
		Reason: "the banner could not be read in full: " + markup + " " + addr,
	}}
	r.Capture.Capabilities = &CapabilitiesSection{
		Resolver: "linux.privilege/v1",
		Capabilities: []CapabilityLine{{
			ID: "capability/execute/host/user/alice", SubjectID: "user/alice",
			Action: "execute", Resource: "host", Effect: "allowed", Privilege: "user",
			Attributes: map[string]string{"homepage": addr, "banner": markup},
			Sources:    []string{"file:/etc/sudoers"},
		}},
		Diagnostics: []trustfreeze.Diagnostic{{Code: "privilege_source_unreadable", Field: addr, Message: markup}},
	}
	page, err := MarshalHTML(r, HTMLOptions{Generator: htmlTestGenerator})
	if err != nil {
		t.Fatal(err)
	}
	s := string(page)
	if found := externalReferences(s); len(found) > 0 {
		t.Fatalf("content was mistaken for a reference: %v", found)
	}
	if strings.Contains(s, markup) {
		t.Fatal("the page carries an unescaped <script> element from a host value")
	}
	if n := strings.Count(s, "&lt;script&gt;alert(1)&lt;/script&gt;"); n < 3 {
		t.Fatalf("the markup-looking value is on the page %d times as escaped text, want at least 3", n)
	}
	if n := strings.Count(s, addr); n < 3 {
		t.Fatalf("the address-looking value is on the page %d times, want at least 3: content must not be dropped", n)
	}
}

// TestReportHTMLKeepsEveryStatusWordAndItsReason: the eight status words stay
// words, and every probe that carries a reason has that reason beside it in
