// TestReportHTMLCarriesTheGuidanceOfItsKind: the guidance exists per bundle
// kind, and the command it names fits that kind. A capture carries no
// signature, so its guidance names no trusted key.
func TestReportHTMLCarriesTheGuidanceOfItsKind(t *testing.T) {
	for _, tc := range []struct {
		kind    trustfreeze.Kind
		wants   []string
		unwants []string
	}{
		{
			kind: trustfreeze.KindCapture,
			wants: []string{
				"A record of what one machine looked like at one moment.",
				"skillctl trust-freeze baseline approve --capture <bundle>",
				"skillctl trust-freeze verify --bundle <bundle>",
			},
			// A capture is not signed, so nothing here takes a key.
			unwants: []string{"--trusted-key"},
		},
		{
			kind: trustfreeze.KindBaseline,
			wants: []string{
				"An approved state.",
				"skillctl trust-freeze verify --bundle <bundle> --trusted-key <public key>",
				"skillctl trust-freeze diff --baseline <baseline> --current <capture> --trusted-key <public key>",
			},
		},
		{
			kind: trustfreeze.KindDiff,
			wants: []string{
				"The difference between an approved baseline and a later capture of the same",
				"skillctl trust-freeze diff --baseline <baseline> --current <capture> --trusted-key <public key>",
			},
			unwants: []string{"skillctl trust-freeze baseline approve --capture"},
		},
	} {
		t.Run(string(tc.kind), func(t *testing.T) {
			page, err := MarshalHTML(kindReport(t, tc.kind), HTMLOptions{Generator: htmlTestGenerator})
			if err != nil {
				t.Fatal(err)
			}
			text := html.UnescapeString(string(page))
			for _, w := range tc.wants {
				if !strings.Contains(text, w) {
					t.Fatalf("the page does not carry %q", w)
				}
			}
			for _, u := range tc.unwants {
				if strings.Contains(text, u) {
					t.Fatalf("the page of a %s carries %q", tc.kind, u)
				}
			}
			for _, heading := range []string{"What this is", "What it answers", "What it does not answer", "What to do next"} {
				if !strings.Contains(text, heading) {
					t.Fatalf("the guidance has no %q section", heading)
				}
			}
		})
	}
}

