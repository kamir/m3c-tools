// htmlTagPattern matches one tag of the markup. Data can never produce a tag:
// html/template escapes "<" in every value it writes, which the hostile-content
// test measures.
var htmlTagPattern = regexp.MustCompile(`<[^>]*>`)

// htmlAttrPattern matches one attribute inside a tag.
var htmlAttrPattern = regexp.MustCompile(`([A-Za-z_:][-\w:.]*)\s*=\s*("([^"]*)"|'([^']*)'|([^\s"'>]+))`)

// htmlLoadingAttrs are the attributes that make a browser fetch something.
var htmlLoadingAttrs = map[string]bool{
	"src": true, "srcset": true, "integrity": true, "background": true,
	"poster": true, "codebase": true, "xlink:href": true, "formaction": true,
	"action": true, "data": true, "manifest": true, "ping": true,
}

// htmlLoadingTags are the elements that pull something in.
var htmlLoadingTags = map[string]bool{
	"script": true, "iframe": true, "object": true, "embed": true, "link": true,
	"base": true, "applet": true, "frame": true, "frameset": true, "img": true,
	"audio": true, "video": true, "source": true, "track": true, "portal": true,
}

// externalReferences returns every external reference of a page. It reads the
// markup and the content of the style blocks, never a text node: an attribute
// value that contains an address is content and has to be shown, escaped.
// Allowed is exactly one form, a jump target inside the document (href="#...").
func externalReferences(page string) []string {
	var found []string
	for _, tag := range htmlTagPattern.FindAllString(page, -1) {
		name := strings.ToLower(strings.TrimLeft(strings.Fields(strings.Trim(tag, "<>/"))[0], "/"))
		if htmlLoadingTags[name] {
			found = append(found, "element <"+name+">: "+tag)
		}
		for _, m := range htmlAttrPattern.FindAllStringSubmatch(tag, -1) {
			attr := strings.ToLower(m[1])
			value := m[3] + m[4] + m[5]
			switch {
			case attr == "href" && strings.HasPrefix(value, "#"):
				// A jump target inside the document, the one allowed form.
			case attr == "href" || htmlLoadingAttrs[attr]:
				found = append(found, "attribute "+attr+"="+value)
			case strings.Contains(value, "://") || strings.HasPrefix(value, "//") ||
				strings.Contains(strings.ToLower(value), "url(") ||
				regexp.MustCompile(`(?i)^(data|file|javascript|vbscript):`).MatchString(value):
				found = append(found, "attribute "+attr+" carries a reference: "+value)
			}
		}
	}
	for _, style := range styleBlocks(page) {
		lower := strings.ToLower(style)
		for _, bad := range []string{"@import", "@font-face", "url(", "://"} {
			if strings.Contains(lower, bad) {
				found = append(found, "style block carries "+bad)
			}
		}
	}
	return found
}

// styleBlocks returns the content of every <style> element of a page.
func styleBlocks(page string) []string {
	var out []string
	rest := page
	for {
		open := strings.Index(strings.ToLower(rest), "<style")
		if open < 0 {
			return out
		}
		start := strings.Index(rest[open:], ">")
		if start < 0 {
			return out
		}
		start += open + 1
		end := strings.Index(strings.ToLower(rest[start:]), "</style")
		if end < 0 {
			return append(out, rest[start:])
		}
		out = append(out, rest[start:start+end])
		rest = rest[start+end:]
	}
}

// attributeNames returns every occurrence of the named attributes in the
// markup of a page.
func attributeNames(page string, names ...string) []string {
	want := map[string]bool{}
	for _, n := range names {
		want[n] = true
	}
	var out []string
	for _, tag := range htmlTagPattern.FindAllString(page, -1) {
		for _, m := range htmlAttrPattern.FindAllStringSubmatch(tag, -1) {
			if want[strings.ToLower(m[1])] {
				out = append(out, m[0])
			}
		}
	}
	return out
}

// validityClaimPatterns are sentences that would claim a signature, a key or a
// bundle is valid. report projects and evaluates nothing, so none of them may
// appear. The word "verify" on its own is allowed: the page names the command
// that does evaluate, which is the opposite of a claim.
var validityClaimPatterns = []*regexp.Regexp{
	regexp.MustCompile(`(?i)signature[^.\n]{0,40}\bis valid\b`),
	regexp.MustCompile(`(?i)signature\s*[:=]\s*valid\b`),
	regexp.MustCompile(`(?i)\bsigned and valid\b`),
	regexp.MustCompile(`(?i)\bvalid signature\b`),
	regexp.MustCompile(`(?i)\bsignature verified\b`),
	regexp.MustCompile(`(?i)\bverified against\b`),
	regexp.MustCompile(`(?i)\bis (?:valid|trusted|authentic|genuine)\b`),
	regexp.MustCompile(`(?i)\bist g(?:ue|.)ltig\b`),
}

// validityClaimNegations are the words that turn one of the patterns above
// into the opposite of a claim: "Whether the signature is valid" is the
// sentence the guidance is required to carry, and "the signature is valid" is
// the sentence it must never carry.
var validityClaimNegations = []string{"whether", "not ", "cannot", "never", "nor ", "unless", "no "}

// validityClaims returns every claim about validity found in a text. A match
// whose immediate context negates or questions it is not a claim.
func validityClaims(text string) []string {
	var found []string
	for _, re := range validityClaimPatterns {
		for _, at := range re.FindAllStringIndex(text, -1) {
			from := at[0] - 28
			if from < 0 {
				from = 0
			}
			before := strings.ToLower(text[from:at[0]])
			negated := false
			for _, n := range validityClaimNegations {
				if strings.Contains(before, n) {
					negated = true
					break
				}
			}
			if !negated {
				found = append(found, re.String()+": "+text[at[0]:at[1]])
			}
		}
	}
	sort.Strings(found)
	return found
}

// reasonsNotOnPage returns, by name, the probe reasons that are not on the page
// in full.
func reasonsNotOnPage(text string, probes []trustfreeze.ProbeSummary) []string {
	var out []string
	for _, p := range probes {
		if p.Reason == "" {
			continue
		}
		if !strings.Contains(text, p.Reason) {
			out = append(out, fmt.Sprintf("%s (%s): %q", p.ProbeID, p.Status, p.Reason))
		}
	}
	return out
}

// digestsOfJSON returns every digest-shaped value of a report, by field path.
func digestsOfJSON(t *testing.T, raw []byte) map[string]string {
	t.Helper()
	var tree any
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	if err := dec.Decode(&tree); err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	var walk func(path string, v any)
	walk = func(path string, v any) {
		switch node := v.(type) {
		case map[string]any:
			for k, e := range node {
				// The digests of the visible sections only: a per-artifact or
				// per-change digest is not on the page, by decision.
				if k == "artifacts" || k == "probe_results" || k == "changes" || k == "findings" {
					continue
				}
				walk(path+"."+k, e)
			}
		case []any:
			for i, e := range node {
				walk(fmt.Sprintf("%s[%d]", path, i), e)
			}
		case string:
			if strings.HasPrefix(node, "sha256:") {
				out[path] = node
			}
		}
	}
	walk("", tree)
	return out
}

